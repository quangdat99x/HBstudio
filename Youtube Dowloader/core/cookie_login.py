"""
Open a YouTube login window and save that session as cookies.txt.

Runs as its own process because pywebview needs its own main loop, and the
Flask server may itself be running headless under Tool Manager:

    python core/cookie_login.py <path/to/cookies.txt>

Prints one JSON line on stdout: {"success": true, "count": 34}

The window runs in private mode, so the login session lives only as long as
the window. That is deliberate: YouTube rotates (and invalidates) the session
of a browser that keeps using it, which is why hand-exported cookies.txt files
go stale after a few days. A session that is never used again stays valid.
"""
import json
import sys
import time
import threading
from datetime import timezone
from email.utils import parsedate_to_datetime

import webview

# Land straight on the Google sign-in form, then bounce back to YouTube so the
# YouTube-side session cookies get planted.
LOGIN_URL = (
    'https://accounts.google.com/ServiceLogin'
    '?service=youtube&continue=https%3A%2F%2Fwww.youtube.com%2F'
)

# These only appear on .youtube.com once a real Google account session is
# attached, and they are exactly what yt-dlp authenticates with. A signed-out
# session only ever carries VISITOR_INFO1_LIVE / YSC / PREF and friends, so
# seeing any one of these is a reliable "the user is logged in now" signal.
SESSION_COOKIES = ('__Secure-3PSID', '__Secure-1PSID', 'SID', 'LOGIN_INFO')

POLL_SECONDS = 2
SETTLE_SECONDS = 3
TIMEOUT_SECONDS = 900

_closed = threading.Event()
RESULT = {'success': False, 'error': 'Cửa sổ đăng nhập đã đóng trước khi lấy được cookie.'}


def _expiry(raw) -> int:
    """WebView2 hands back an RFC-1123 string; 0 means a session cookie."""
    try:
        dt = parsedate_to_datetime(str(raw))
    except Exception:
        return 0
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    try:
        ts = int(dt.timestamp())
    except (OverflowError, ValueError, OSError):
        return 0
    return ts if ts > time.time() else 0


def _morsels(cookies):
    """pywebview returns a list of SimpleCookie; yield (name, morsel) pairs."""
    for jar in cookies or []:
        for name, morsel in jar.items():
            yield name, morsel


def _write_netscape(cookies, path) -> int:
    """Write cookies in the Netscape format yt-dlp expects."""
    lines = [
        '# Netscape HTTP Cookie File',
        '# Generated by YouTube Downloader. Do not edit.',
        '',
    ]
    count = 0
    for name, m in _morsels(cookies):
        domain = m['domain'] or '.youtube.com'
        lines.append('\t'.join([
            domain,
            'TRUE' if domain.startswith('.') else 'FALSE',
            m['path'] or '/',
            'TRUE' if m['secure'] else 'FALSE',
            str(_expiry(m['expires'])),
            name,
            m.value,
        ]))
        count += 1

    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    return count


def _read_cookies(window):
    try:
        return list(window.get_cookies())
    except Exception:
        return []


def _watch(window, out_path):
    """Poll until the window holds a signed-in YouTube session, then save it."""
    global RESULT
    deadline = time.time() + TIMEOUT_SECONDS

    while time.time() < deadline:
        time.sleep(POLL_SECONDS)

        if _closed.is_set():
            return

        try:
            url = window.get_current_url() or ''
        except Exception:
            continue

        # Still somewhere in the Google sign-in flow.
        if 'youtube.com' not in url:
            continue

        names = {name for name, _ in _morsels(_read_cookies(window))}
        if not any(sid in names for sid in SESSION_COOKIES):
            continue

        # Give YouTube a moment to finish planting the rest of the session.
        try:
            window.evaluate_js(
                "document.body.insertAdjacentHTML('afterbegin',"
                "'<div style=\"position:fixed;inset:0;z-index:99999;display:flex;"
                "align-items:center;justify-content:center;background:rgba(10,10,15,.92);"
                "color:#fff;font:600 20px system-ui\">Da lay cookie thanh cong. "
                "Dang dong cua so...</div>')"
            )
        except Exception:
            pass
        time.sleep(SETTLE_SECONDS)
        try:
            count = _write_netscape(_read_cookies(window), out_path)
            RESULT = {'success': True, 'count': count}
        except Exception as e:
            RESULT = {'success': False, 'error': f'Không ghi được cookies.txt: {e}'}

        try:
            window.destroy()
        except Exception:
            pass
        return

    RESULT = {'success': False, 'error': 'Hết thời gian chờ đăng nhập (15 phút).'}
    try:
        window.destroy()
    except Exception:
        pass


def main():
    if len(sys.argv) < 2:
        print(json.dumps({'success': False, 'error': 'Thiếu đường dẫn cookies.txt'}))
        return

    out_path = sys.argv[1]

    window = webview.create_window(
        'Đăng nhập YouTube — cookie sẽ được lưu tự động',
        LOGIN_URL,
        width=1100,
        height=850,
        min_size=(900, 700),
    )
    window.events.closed += lambda *a: _closed.set()

    # private_mode wipes the profile on exit, so this login is never reused.
    webview.start(_watch, (window, out_path), private_mode=True)

    print(json.dumps(RESULT, ensure_ascii=False))


if __name__ == '__main__':
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass
    main()
